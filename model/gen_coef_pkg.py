"""
Generates rtl/mf_coef_pkg.vhd from vectors/mf_coef.txt so the VHDL
coefficients always match the golden model (no hand-copied constants).
Run radar_model.py first.
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
coef = np.loadtxt(ROOT / "vectors" / "mf_coef.txt", dtype=np.int64)
hI, hQ = coef[:, 0], coef[:, 1]
n = len(hI)


def vhdl_array(vals):
    rows = []
    for i in range(0, n, 8):
        rows.append("    " + ", ".join(f"{v:6d}" for v in vals[i:i + 8]))
    return "(\n" + ",\n".join(rows) + "\n  )"


pkg = f"""-- Auto-generated by model/gen_coef_pkg.py from vectors/mf_coef.txt. Do not edit by hand.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

package mf_coef_pkg is
  constant N_TAPS    : integer := {n};
  constant IQ_W      : integer := 12;  -- input I/Q width (signed)
  constant COEF_W    : integer := 12;  -- coefficient width (signed)
  constant PROD_W    : integer := IQ_W + COEF_W;      -- 24-bit real products
  constant ACC_W     : integer := 31;  -- 24 + 1 (complex add) + 6 (64 taps)
  constant OUT_SHIFT : integer := 15;
  constant OUT_W     : integer := ACC_W - OUT_SHIFT;  -- 16-bit output

  type coef_array_t is array (0 to N_TAPS-1) of integer;

  -- h[k] for k = 0..N_TAPS-1 (convolution order)
  constant H_I : coef_array_t := {vhdl_array(hI)};

  constant H_Q : coef_array_t := {vhdl_array(hQ)};
end package mf_coef_pkg;
"""

out = ROOT / "rtl" / "mf_coef_pkg.vhd"
out.parent.mkdir(exist_ok=True)
out.write_text(pkg)
print(f"Wrote {out} ({n} taps)")
